# 2) Cumulative return over time

def cumulative_return(df):
    df = df.sort_values(['symbol', 'date'])

    df['daily_return'] = df.groupby('symbol')['close'].pct_change()

    df['cum_return'] = (1 + df['daily_return']).groupby(df['symbol']).cumprod()

    return df
df = cumulative_return(df)
print(df)

# Visualization (Top 5 cumulative returns)

def plot_top5_cumulative(df):
    top5 = df.groupby('symbol')['cum_return'].last() \
             .sort_values(ascending=False) \
             .head(5).index

    import matplotlib.pyplot as plt
    for stock in top5:
        temp = df[df['symbol'] == stock]
        plt.plot(temp['date'], temp['cum_return'], label=stock)
    plt.legend()
    plt.title("Top 5 Cumulative Returns")
    plt.xlabel("Date")
    plt.ylabel("Cumulative Return")
    plt.show()

plot_top5_cumulative(df)

