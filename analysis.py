import pandas as pd

def monthly_gainers_losers(df):
    df['date'] = pd.to_datetime(df['date'])
    df['month'] = df['date'].dt.to_period('M')

    # monthly first and last price
    monthly = df.groupby(['symbol', 'month']).agg(
        first_price=('close', 'first'),
        last_price=('close', 'last')
    )

    monthly['monthly_return'] = (
        (monthly['last_price'] - monthly['first_price']
    ) / monthly['first_price']
    ) * 100

    result = {}

    for m in monthly.index.get_level_values('month').unique():
        temp = monthly.xs(m, level='month')

        top5 = temp['monthly_return'].sort_values(ascending=False).head(5)
        bottom5 = temp['monthly_return'].sort_values().head(5)

        result[str(m)] = {
            "gainers": top5,
            "losers": bottom5
        }

    return result

res = monthly_gainers_losers(df)
print(res)

import matplotlib.pyplot as plt
import pandas as pd

def plot_monthly_dashboard(result):

    months = list(result.keys())

    fig, axes = plt.subplots(len(months), 1, figsize=(10, 40))

    for i, month in enumerate(months):

        gainers = result[month]['gainers']
        losers = result[month]['losers']

        combined = pd.concat([gainers, losers])

        colors = ['green' if x > 0 else 'red' for x in combined]

        combined.plot(
            kind='bar',
            ax=axes[i],
            color=colors
        )

        axes[i].set_title(f"{month} Top Gainers & Losers")

        axes[i].set_xlabel("Stocks")

        axes[i].set_ylabel("Monthly Return (%)")

    plt.tight_layout()

    plt.show()

# Visualization (Top 5 Gainers and Losers by Month)

plot_monthly_dashboard(res)

